package com.openminis.app.data

/**
 * [T-send-gate-deadlock] Решение «можно ли отправлять сообщение», выделенное в
 * чистую логику — чтобы его можно было проверить тестом без Android.
 *
 * ## Дефект, который это закрывает
 *
 * Коммит `fb6548d8` ввёл ВТОРОЙ гейт отправки `fullHistoryReady` рядом с
 * существующим `sessionLoaded`. Открытие нового гейта поставили ВНУТРИ `try`,
 * а `sessionLoaded` открывается строкой ниже — в `finally`, с явной пометкой
 * «открываем даже при раннем выходе и исключении». Защиту скопировали
 * визуально, но она относится только к первому флагу; `catch` в этом `try`
 * не было вовсе.
 *
 * Результат: сессия ВЫГЛЯДИТ загруженной (`sessionLoaded=true`), а отправка
 * молча отбивается «история ещё загружается» и текст возвращается в поле
 * ввода. Навсегда — потому что ViewModel живёт в кэше и переоткрытие сессии
 * отдаёт ту же модель с закрытым гейтом.
 *
 * Четыре пути в это состояние (все найдены в коде):
 *   1. `getSession(sessionId) == null` → ранний `return@launch`;
 *   2. любое исключение вне двух обрабатываемых шаблонов;
 *   3. safe-mode: `return` стоит ДО запуска корутины — не открывается ни один
 *      гейт;
 *   4. кэш ViewModel: перезапуск не лечит.
 *
 * ## Почему трёх состояний, а не булева флага
 *
 * Булев флаг не различает «жди, сейчас загрузится» и «загрузка провалилась,
 * ждать бессмысленно». Первое обязано блокировать отправку (иначе уйдёт
 * запрос с неполным контекстом), второе — обязано её РАЗРЕШИТЬ, иначе сессия
 * мертва. Поэтому:
 *
 *   LOADING  — история грузится: блокировать, это временно и честно;
 *   READY    — полная история в памяти: разрешать молча;
 *   DEGRADED — загрузить не удалось: разрешать, но ОДИН раз предупредить, что
 *              модель не увидит старую часть переписки.
 *
 * Так мы не меняем старый баг на новый: отправка с частичным контекстом
 * происходит только когда полного контекста в принципе не будет, и
 * пользователь об этом уведомлён.
 */
object SendGatePolicy {

    enum class HistoryState {
        /** История ещё читается из БД — отправку задержать. */
        LOADING,

        /** Полная история в памяти — отправлять можно. */
        READY,

        /** Загрузка провалилась/пропущена — отправлять можно, но с предупреждением. */
        DEGRADED,
    }

    enum class Decision {
        /** Отправлять. Контекст полный. */
        ALLOW,

        /** Отправлять, но сначала показать предупреждение о неполном контексте. */
        ALLOW_WITH_WARNING,

        /** Не отправлять, показать «история ещё загружается». */
        BLOCK_LOADING,

        /**
         * Не выполнять: операция ПЕРЕЗАПИСЫВАЕТ историю, а история неполная.
         * Отличается от [BLOCK_LOADING] тем, что ожидание не поможет —
         * пользователю нужно другое действие (новый чат / перезаход в сессию).
         */
        BLOCK_UNSAFE_REWRITE,
    }

    /**
     * Что именно защищаем. Разделение обязательно: смягчение гейта корректно
     * ТОЛЬКО для отправки. Для операций, перезаписывающих историю (compact /
     * rescue), «разрешить при неполной истории» = НОВЫЙ баг: `compactAll`
     * считает якорь по `agentHistory` в памяти и пишет маркер сжатия по этому
     * якорю; rescue вдобавок сгружает крупные payload'ы на диск. При неполной
     * истории якорь ляжет мимо реальных данных — маркер (и то, что попадёт в
     * сводку) окажется рассчитан по обрезку, которого нет в памяти. Поэтому
     * такие операции остаются заблокированными в DEGRADED.
     *
     * NB: физического удаления строк при сжатии больше нет — сырьё всегда
     * остаётся на диске (сжатие обратимо через revertCompact). Но защита гейта
     * сохраняется: неверный якорь по неполной истории всё равно испортит
     * границу сжатия.
     */
    enum class Operation {
        /** Отправка сообщения: читает историю, ничего не портит. */
        SEND,

        /** Сжатие/rescue: ПЕРЕЗАПИСЫВАЕТ историю и удаляет строки из БД. */
        REWRITE_HISTORY,
    }

    /**
     * @param state текущее состояние истории сессии
     * @param warningAlreadyShown было ли уже показано предупреждение в этом
     *        экземпляре ViewModel (второй раз не спамим)
     * @param operation что защищаем — см. [Operation]. По умолчанию [Operation.SEND],
     *        потому что это единственный путь, для которого смягчение безопасно.
     */
    fun decide(
        state: HistoryState,
        warningAlreadyShown: Boolean,
        operation: Operation = Operation.SEND,
    ): Decision = when (state) {
        HistoryState.READY -> Decision.ALLOW
        HistoryState.LOADING -> Decision.BLOCK_LOADING
        HistoryState.DEGRADED -> when (operation) {
            // Отправка: разрешаем — иначе сессия мертва навсегда (исходный баг).
            Operation.SEND ->
                if (warningAlreadyShown) Decision.ALLOW else Decision.ALLOW_WITH_WARNING
            // Перезапись истории: запрещаем — иначе безвозвратно удалим строки,
            // которых нет в памяти. Ожидание не поможет, поэтому НЕ BLOCK_LOADING.
            Operation.REWRITE_HISTORY -> Decision.BLOCK_UNSAFE_REWRITE
        }
    }

    /**
     * Состояние из двух флагов ViewModel. `degraded` имеет приоритет над
     * `ready`: если загрузка провалилась, «готовности» нет даже когда часть
     * данных доехала.
     */
    fun stateOf(fullHistoryReady: Boolean, degraded: Boolean): HistoryState = when {
        degraded -> HistoryState.DEGRADED
        fullHistoryReady -> HistoryState.READY
        else -> HistoryState.LOADING
    }

    /** Отправка разрешена в любом состоянии, кроме честной загрузки. */
    fun maySend(state: HistoryState): Boolean = state != HistoryState.LOADING

    /** Перезаписывать историю можно ТОЛЬКО когда она полная. */
    fun mayRewriteHistory(state: HistoryState): Boolean = state == HistoryState.READY
}
